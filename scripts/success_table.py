"""Grasp success table with 95 % Wilson intervals, from the evaluation summaries in results/.

python scripts/success_table.py            # prints the Markdown table, writes results/success_table.md

Reads results/{scripted,residual}_{noisy,noiseless}.json (written by scripts/evaluate.py --out).
The interval is per row and per support; the two rows use the same episode seeds, so the intervals
are conservative for the difference between them.
"""

import json
import math
from pathlib import Path

RESULTS = Path(__file__).resolve().parents[1] / "results"
ROWS = (("scripted", "Scripted grasp (baseline)"), ("residual", "PPO residual on the scripted grasp"))
SUPPORTS = ("bottle", "post", "bridge")


def wilson(p: float, n: int, z: float = 1.96) -> tuple[float, float]:
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return c - h, c + h


def cell(p: float, n: int) -> str:
    lo, hi = wilson(p, n)
    return f"{100 * p:.1f} % [{100 * lo:.0f}, {100 * hi:.0f}]"


def main():
    noisy_n = json.loads((RESULTS / "scripted_noisy.json").read_text())["episodes"]
    exact_n = json.loads((RESULTS / "scripted_noiseless.json").read_text())["episodes"]
    head = [f"Camera error (N = {noisy_n})"]
    head += [f"{s.capitalize()} (N = {json.loads((RESULTS / 'scripted_noisy.json').read_text())['per_support'][s]['n']})"
             for s in SUPPORTS]
    head += [f"Exact pose (N = {exact_n})"]
    lines = ["| | " + " | ".join(head) + " |", "|---" * (len(head) + 1) + "|"]
    for key, label in ROWS:
        noisy = json.loads((RESULTS / f"{key}_noisy.json").read_text())
        exact = json.loads((RESULTS / f"{key}_noiseless.json").read_text())
        cells = [cell(noisy["success"], noisy["episodes"])]
        cells += [cell(noisy["per_support"][s]["success"], noisy["per_support"][s]["n"]) for s in SUPPORTS]
        cells += [cell(exact["success"], exact["episodes"])]
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    table = "\n".join(lines)
    print(table)
    (RESULTS / "success_table.md").write_text(
        "Grasp success rate, 95 % Wilson interval in brackets. Generated by scripts/success_table.py.\n\n"
        + table + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
